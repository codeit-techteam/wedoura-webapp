// Builds src/data/photos.ts from the placeholder photographs in public/photos.
// For each JPG it records the real width and height (layouts follow the
// aspect ratio; nothing is cropped square) and a tiny blurred placeholder.
// Alt text comes from public/photos/alt.json. Run: npm run photos
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname, basename, extname } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "public/photos");
const altPath = join(dir, "alt.json");
const alt = JSON.parse(readFileSync(altPath, "utf8"));

const files = readdirSync(dir)
  .filter((f) => /\.(jpe?g|png|webp)$/i.test(f))
  .sort();

const entries = [];
for (const file of files) {
  const id = basename(file, extname(file));
  const img = sharp(join(dir, file));
  const { width, height } = await img.metadata();
  const blur = await img.resize(12, null, { fit: "inside" }).jpeg({ quality: 40 }).toBuffer();
  if (!alt[id]) throw new Error(`Missing alt text for ${file} in public/photos/alt.json`);
  // Entries are either "alt string" or { alt, credit } (photographer / source).
  const meta = typeof alt[id] === "string" ? { alt: alt[id] } : alt[id];
  if (!meta.alt) throw new Error(`Missing alt text for ${file} in public/photos/alt.json`);
  entries.push({ id, src: `/photos/${file}`, width, height, alt: meta.alt, credit: meta.credit, blurDataURL: `data:image/jpeg;base64,${blur.toString("base64")}` });
}

const out = `// GENERATED by scripts/photos.mjs from public/photos. Do not edit by hand.
import type { Photo } from "./types";

export const photos = {
${entries
  .map(
    (p) => `  ${p.id}: {
    id: "${p.id}",
    src: "${p.src}",
    width: ${p.width},
    height: ${p.height},
    alt: ${JSON.stringify(p.alt)},${p.credit ? `
    credit: ${JSON.stringify(p.credit)},` : ""}
    blurDataURL:
      "${p.blurDataURL}",
  },`,
  )
  .join("\n")}
} satisfies Record<string, Photo>;

export type PhotoId = keyof typeof photos;
export const photoList: Photo[] = Object.values(photos);
`;

writeFileSync(join(root, "src/data/photos.ts"), out);
console.log(`wrote ${entries.length} photos to src/data/photos.ts`);
