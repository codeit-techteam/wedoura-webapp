// Builds src/data/photos.ts from the placeholder photographs in public/photos
// and the equirectangular panoramas in public/360. For each JPG it records the
// real width and height (layouts follow the aspect ratio; nothing is cropped
// square) and a tiny blurred placeholder. Panoramas additionally carry
// projection: "equirectangular" and must be 2:1 and at least 4000px wide.
// Alt text comes from alt.json in each folder. Run: npm run photos
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname, basename, extname } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

async function collect(dir, srcPrefix, { equirect = false } = {}) {
  if (!existsSync(join(dir, "alt.json"))) {
    if (equirect) return []; // No panoramas yet; nothing to list.
    throw new Error(`Missing ${join(dir, "alt.json")}`);
  }
  const alt = JSON.parse(readFileSync(join(dir, "alt.json"), "utf8"));
  const files = readdirSync(dir)
    .filter((f) => /\.(jpe?g|png|webp)$/i.test(f))
    .sort();

  const entries = [];
  for (const file of files) {
    const id = basename(file, extname(file));
    const img = sharp(join(dir, file));
    const { width, height } = await img.metadata();
    if (equirect) {
      if (Math.abs(width / (2 * height) - 1) > 0.01) throw new Error(`${file} is not 2:1 (${width}×${height})`);
      if (width < 4000) throw new Error(`${file} is only ${width}px wide; panoramas need at least 4000px`);
    }
    const blur = await img.resize(12, null, { fit: "inside" }).jpeg({ quality: 40 }).toBuffer();
    if (!alt[id]) throw new Error(`Missing alt text for ${file} in ${dir}/alt.json`);
    // Entries are either "alt string" or { alt, credit } (photographer / source).
    const meta = typeof alt[id] === "string" ? { alt: alt[id] } : alt[id];
    if (!meta.alt) throw new Error(`Missing alt text for ${file} in ${dir}/alt.json`);
    entries.push({
      id,
      src: `${srcPrefix}/${file}`,
      width,
      height,
      alt: meta.alt,
      credit: meta.credit,
      equirect,
      blurDataURL: `data:image/jpeg;base64,${blur.toString("base64")}`,
    });
  }
  return entries;
}

const entries = [
  ...(await collect(join(root, "public/photos"), "/photos")),
  ...(await collect(join(root, "public/360"), "/360", { equirect: true })),
];

const out = `// GENERATED by scripts/photos.mjs from public/photos and public/360. Do not edit by hand.
import type { Photo } from "./types";

export const photos = {
${entries
  .map(
    (p) => `  ${p.id}: {
    id: "${p.id}",
    src: "${p.src}",
    width: ${p.width},
    height: ${p.height},
    alt: ${JSON.stringify(p.alt)},${p.credit ? `
    credit: ${JSON.stringify(p.credit)},` : ""}${p.equirect ? `
    projection: "equirectangular",` : ""}
    blurDataURL:
      "${p.blurDataURL}",
  },`,
  )
  .join("\n")}
} satisfies Record<string, Photo>;

export type PhotoId = keyof typeof photos;
export const photoList: Photo[] = Object.values(photos);
`;

writeFileSync(join(root, "src/data/photos.ts"), out);
console.log(`wrote ${entries.length} photos to src/data/photos.ts`);
