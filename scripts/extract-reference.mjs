// Extracts markup, CSS, JS and tokens from the client's mockups in
// docs/reference/*.html into small files in docs/reference/extracted.
// The originals are ~2 MB each because of embedded base64 images; never read
// them whole. Run: npm run extract-reference
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(root, "docs/reference");
const out = join(src, "extracted");
mkdirSync(out, { recursive: true });

const files = [
  ["Wedoura Homepage.html", "homepage", "Desktop homepage mockup"],
  ["Wedoura Photographer Profilefinal1.html", "photographer-profile", "Photographer profile (vendor portfolio) mockup"],
  ["Wedoura2h.html", "mobile-app", "430px phone mockup with home, vendors, story and profile screens"],
];

const DATA_URI = /data:(image|video|font)\/[a-zA-Z0-9.+-]+;base64,[A-Za-z0-9+/=\s]+/g;
const stripData = (s) => s.replace(DATA_URI, "PHOTO_PLACEHOLDER");

const kb = (s) => (Buffer.byteLength(s) / 1024).toFixed(1) + " KB";
const tokensMd = [
  "# Tokens and patterns extracted from the client mockups",
  "",
  "Generated by `scripts/extract-reference.mjs`. The brief (`docs/reference/brief.md`) takes precedence wherever a value differs.",
  "",
  "| Role | Brief (authoritative) |",
  "|---|---|",
  "| Background | `#FFFFFF` |",
  "| Ivory band | `#F6F2EA` |",
  "| Ink (text) | `#161616` |",
  "| Muted text | `#6B665D` |",
  "| Hairline | `#DDD6C8` |",
  "| Gold accent (small marks only) | `#A8864A` |",
  "",
];

for (const [file, name, title] of files) {
  const raw = readFileSync(join(src, file), "utf8");
  const html = stripData(raw);

  const styles = [...html.matchAll(/<style[^>]*>([\s\S]*?)<\/style>/gi)].map((m) => m[1]).join("\n\n");
  const scripts = [...html.matchAll(/<script[^>]*>([\s\S]*?)<\/script>/gi)].map((m) => m[1]).join("\n\n");
  const markup = html
    .replace(/<style[^>]*>[\s\S]*?<\/style>/gi, "<!-- styles: see " + name + ".css -->")
    .replace(/<script[^>]*>[\s\S]*?<\/script>/gi, "<!-- script: see " + name + ".js -->")
    .replace(/>\s*</g, ">\n<");

  // Light CSS formatting: one rule per line.
  const css = styles.replace(/\}\s*/g, "}\n").replace(/\/\*/g, "\n/*").trim() + "\n";
  // Collapse the placeholder image array in the script.
  const js = scripts.replace(/\[\s*("PHOTO_PLACEHOLDER"\s*,?\s*)+\]/g, "[/* PHOTO_PLACEHOLDER x N */]").trim() + "\n";

  writeFileSync(join(out, `${name}.markup.html`), markup);
  writeFileSync(join(out, `${name}.css`), css);
  writeFileSync(join(out, `${name}.js`), js);

  const rootVars = [...styles.matchAll(/--([a-zA-Z0-9-]+)\s*:\s*([^;}]+)/g)]
    .filter((m) => !m[0].includes("var(--"))
    .map((m) => [m[1], m[2].trim()]);
  const uniq = new Map(rootVars);
  const fonts = [...raw.matchAll(/fonts\.googleapis\.com\/css2\?[^"']+/g)].map((m) => m[0]);
  const keyframes = [...styles.matchAll(/@keyframes\s+([a-zA-Z0-9_-]+)\s*\{([^}]*\}[^}]*)\}/g)].map((m) => `${m[1]} { ${m[2].replace(/\s+/g, " ").trim()} }`);
  const easings = new Set([...styles.matchAll(/cubic-bezier\([^)]*\)/g)].map((m) => m[0]));
  const durations = new Set([...styles.matchAll(/transition:\s*([^;}]+)/g)].map((m) => m[1].trim()));
  const scales = new Set([...styles.matchAll(/scale\(([^)]*)\)/g)].map((m) => m[1]));
  const sections = [...html.matchAll(/<section([^>]*)>/g)].map((m) => m[1].trim());
  const fontSizes = new Set([...styles.matchAll(/font:\s*([^;}]+)/g)].map((m) => m[1].trim()));

  tokensMd.push(`## ${title} (\`${name}.*\`)`, "", `Source: \`${file}\` (${kb(raw)} raw → ${kb(markup)} markup, ${kb(css)} css, ${kb(js)} js)`, "", "### CSS variables", "", "| Variable | Value |", "|---|---|");
  for (const [k, v] of uniq) tokensMd.push(`| \`--${k}\` | \`${v}\` |`);
  tokensMd.push("", "### Fonts", "", ...fonts.map((f) => `- \`${f}\``), "", "### Section order", "", ...sections.map((s, i) => `${i + 1}. \`<section ${s}>\``), "");
  if (keyframes.length) tokensMd.push("### Keyframes", "", ...keyframes.map((k) => `- \`${k}\``), "");
  tokensMd.push("### Easing", "", ...[...easings].map((e) => `- \`${e}\``), "", "### Transitions", "", ...[...durations].map((d) => `- \`${d}\``), "", "### Scale values", "", `- ${[...scales].map((s) => `\`${s}\``).join(", ")}`, "", "### Font shorthands (type scale)", "", ...[...fontSizes].map((f) => `- \`${f}\``), "");
}

writeFileSync(join(out, "tokens.md"), tokensMd.join("\n"));
writeFileSync(
  join(out, "README.md"),
  `# Extracted reference\n\nThe three client mockups in \`docs/reference/*.html\` are ~2 MB each because of embedded base64 images. **Do not open them whole.** Use these extracts instead:\n\n- \`tokens.md\` — CSS variables, fonts, section order, easing, durations, type scale per mockup, with the brief's authoritative values at the top.\n- \`<name>.markup.html\` — body markup, images replaced by \`PHOTO_PLACEHOLDER\`.\n- \`<name>.css\` — the mockup's stylesheet, one rule per line.\n- \`<name>.js\` — the mockup's script (image arrays collapsed).\n\nNames: \`homepage\`, \`photographer-profile\`, \`mobile-app\`. Regenerate with \`npm run extract-reference\`.\n\nThe mockups are for tone, type, spacing and section ideas only. Do not copy them line by line. Where a value differs from \`docs/reference/brief.md\`, the brief wins.\n`,
);
console.log("extracted to", out);
